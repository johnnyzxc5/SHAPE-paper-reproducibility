function hex = trajectory_content_hash(artifact)
%TRAJECTORY_CONTENT_HASH SHA-256 over ordered canonical trajectory identity.
% Numeric arrays are column-major IEEE float64 encoded little-endian.
r=artifact.reference; q=artifact.qualification;
hex=shape.sha256_canonical("SHAPE_FROZEN_TRAJECTORY_CONTENT_V2", ...
    uint64(artifact.parent_trajectory_id),uint64(artifact.trajectory_seed), ...
    uint64(q.accepted_attempt),uint64(artifact.K_segments),artifact.trajectory_mode, ...
    artifact.rng_algorithm,double(q.t_knots),double(q.q_waypoints), ...
    double(q.velocity_boundary_conditions),double(q.acceleration_boundary_conditions), ...
    double(r.q),double(r.dq),double(r.ddq));
end
