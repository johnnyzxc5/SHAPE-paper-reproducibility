function validate_output(path,uid,cfg,record)
%VALIDATE_OUTPUT Detect incomplete/corrupt run chunks before resume skips.
assert(isfile(path),'Output does not exist.'); info=h5info(path);
got=string(h5readatt(path,'/','run_uid')); assert(got==string(uid),'UID mismatch.');
checks={{'/temporal/shape',[6 cfg.n_time]},{'/temporal/torque',[6 cfg.n_time]}, ...
 {'/temporal/gmo',[6 cfg.n_time]},{'/temporal/energy',[1 cfg.n_time]}, ...
 {'/cwt/shape_log',[6 cfg.output_size]},{'/cwt/torque_log',[6 cfg.output_size]}, ...
 {'/cwt/gmo_log',[6 cfg.output_size]},{'/cwt/energy_log',cfg.output_size}, ...
 {'/cwt/shape_magnitude',[6 cfg.output_size]},{'/cwt/torque_magnitude',[6 cfg.output_size]}, ...
 {'/cwt/gmo_magnitude',[6 cfg.output_size]},{'/cwt/energy_magnitude',cfg.output_size}, ...
 {'/views/shape_fft_amplitude',[6 1001]},{'/coordinates/fft_frequency_hz',[1 1001]}, ...
 {'/coordinates/cwt_frequency_hz',[1 cfg.output_size(1)]},{'/coordinates/cwt_time_s',[1 cfg.output_size(2)]}, ...
 {'/coordinates/telemetry_time_s',[1 cfg.n_time]},{'/quality/coi_valid_mask',cfg.output_size}, ...
 {'/telemetry/q_meas',[6 cfg.n_time]},{'/telemetry/dq_meas',[6 cfg.n_time]}, ...
 {'/telemetry/tau_cmd',[6 cfg.n_time]},{'/reference/q_ref',[6 cfg.n_time]}, ...
 {'/reference/dq_ref',[6 cfg.n_time]},{'/reference/ddq_ref',[6 cfg.n_time]}, ...
 {'/reference/tau_nom',[6 cfg.n_time]}};
for k=1:numel(checks)
    d=h5info(path,checks{k}{1}); actual=d.Dataspace.Size;
    expected=checks{k}{2};
    actual=actual(actual~=1); expected=expected(expected~=1);
    assert(isequal(actual,expected),'Dataset shape mismatch at %s.',checks{k}{1});
    value=h5read(path,checks{k}{1});
    assert(all(isfinite(double(value(:)))),'Nonfinite value at %s.',checks{k}{1});
end
assert(~isempty(info.Attributes));
t=double(h5read(path,'/coordinates/telemetry_time_s'));
assert(numel(t)==cfg.n_time && abs(t(1))<=eps && abs(t(end)-cfg.duration_s)<=1e-6, ...
    'Telemetry endpoints are invalid.');
assert(string(h5readatt(path,'/','normalization'))=="fixed_hardware_limits_doc09");
assert(string(h5readatt(path,'/','solver'))=="ode45");
if nargin>=4 && ~isempty(record)
    assert(double(h5readatt(path,'/','parent_trajectory_id'))==double(record.parent_trajectory_id));
    assert(string(h5readatt(path,'/','fault_class'))==string(record.fault_class));
    if contains(upper(string(cfg.active_manifest_path)),'PILOT24')
        assert(string(h5readatt(path,'/','trajectory_binding_sha256'))== ...
            "e51122549278d5ae2597605bbeaa75f4f4fff1e244657dad399a2428d85e15ef");
        assert(string(h5readatt(path,'/','generator_sha256'))== ...
            "809483cef2eb13d099938ced21c254dcc33fe01e473415e261057e5a614c46fd");
        assert(string(h5readatt(path,'/','constraint_contract_sha256'))== ...
            "b353095eaaca28d6c2cb241b5f2d4b724e7bbc9d2c8998fde67c57d28c05b65a");
        assert(string(h5readatt(path,'/','trajectory_model_sha256'))== ...
            "534d87131c1d90f8c3b13611e4d3e9087c8e983f22bf51bf41023bcb672fc569");
        assert(double(h5readatt(path,'/','trajectory_K_segments'))==double(record.K_segments));
        assert(string(h5readatt(path,'/','trajectory_mode'))==string(record.trajectory_mode));
    end
end
end
