function decision = observer_ctdq_environment_policy(env,cfg)
%OBSERVER_CTDQ_ENVIRONMENT_POLICY Govern frozen-MEX runtime environments.
% This policy does not qualify a host for production.  It only identifies
% environments in which the immutable observer MEX may be loaded and put
% through its frozen fixture self-test.  Candidate hosts still require the
% official four-run PHYSICAL host qualification before production.

arguments
    env struct
    cfg struct
end

historical = strcmpi(string(env.arch),string(cfg.observer_ctdq_qualified_arch)) && ...
    strcmp(string(env.matlab_version),string(cfg.observer_ctdq_qualified_matlab)) && ...
    startsWith(string(env.coder_version),string(cfg.observer_ctdq_qualified_coder_major_minor)) && ...
    strcmpi(string(env.compiler_name),string(cfg.observer_ctdq_qualified_compiler)) && ...
    strcmp(string(env.compiler_version),string(cfg.observer_ctdq_qualified_compiler_version));

candidate_update5 = strcmpi(string(env.arch),"win64") && ...
    strcmp(string(env.matlab_version),"26.1.0.3346908 (R2026a) Update 5") && ...
    startsWith(string(env.coder_version),"26.1") && ...
    contains(lower(string(env.compiler_name)),"microsoft visual c++ 2022") && ...
    startsWith(string(env.compiler_version),"17.0");

decision = struct( ...
    'supported',logical(historical || candidate_update5), ...
    'profile','UNSUPPORTED', ...
    'historical_authority',logical(historical), ...
    'candidate_environment',logical(candidate_update5), ...
    'requires_fresh_physical_host_qualification',true, ...
    'mex_recompilation_required',false, ...
    'mingw_required_for_runtime',false, ...
    'mingw_required_for_historical_mex_recompilation_only',true, ...
    'broad_domain_update5_observation','AD_HOC_2000_STATE_MAX_ABS_7.1054273576010019E-09_NM_NOT_AN_AUTHORITY_GATE', ...
    'frozen_fixture_tolerance_Nm',double(cfg.observer_ctdq_selftest_tolerance_Nm));
if historical
    decision.profile='HISTORICAL_UPDATE4_MINGW_RATIFIED';
    decision.requires_fresh_physical_host_qualification=false;
elseif candidate_update5
    decision.profile='COLLABORATOR_UPDATE5_MSVC_CANDIDATE_REQUIRES_PHYSICAL';
end
end
