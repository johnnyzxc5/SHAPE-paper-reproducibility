function report=verify_host_concurrency_receipt(path,environment,spec,requested_workers)
%VERIFY_HOST_CONCURRENCY_RECEIPT Enforce exact host-bound process concurrency.
assert(~isempty(path) && isfile(path),'shape:production:HostReceiptRequired', ...
    'A host-specific concurrency qualification receipt is required.');
q=jsondecode(fileread(path));
assert(strcmp(q.schema_version,'production-host-concurrency-qualification-v2'), ...
    'shape:production:HostReceiptSchema','Unsupported host qualification receipt schema.');
assert(strcmp(q.status,'HOST_CONCURRENCY_QUALIFICATION_PASS') && logical(q.pass) && ...
    logical(q.production_qualified), ...
    'shape:production:HostReceiptFail','Host concurrency qualification did not pass.');
assert(strcmp(q.concurrency_authority,'HOST_SPECIFIC_QUALIFIED_CONCURRENCY'), ...
    'shape:production:ConcurrencyAuthority','Receipt does not use host-specific concurrency governance.');
assert(logical(q.exact_concurrency_only) && ~logical(q.production_authorized), ...
    'shape:production:ConcurrencyAuthority', ...
    'Receipt must authorize exact concurrency only and must not itself authorize production.');
assert(double(q.qualified_workers)==double(requested_workers), ...
    'shape:production:WorkerCountNotQualified', ...
    'Receipt qualifies exactly %d workers, not requested %d.',q.qualified_workers,requested_workers);
assert(strcmp(q.worker_profile,'Processes'), ...
    'shape:production:WorkerProfile','Receipt does not qualify Process workers.');
current=environment.host_identity;
assert(strcmpi(q.host_identity.fingerprint_sha256,current.fingerprint_sha256) && ...
    strcmpi(q.hostname,current.hostname), ...
    'shape:production:HostFingerprint','Receipt belongs to a different physical host.');
assert(strcmp(q.matlab_version,environment.matlab_version) && ...
    strcmp(q.matlab_release,environment.release) && ...
    strcmp(q.architecture,environment.architecture), ...
    'shape:production:RuntimeMismatch','MATLAB release/version/architecture differs from the receipt.');
assert(strcmp(q.compiler_name,environment.compiler_name) && ...
    strcmp(q.compiler_version,environment.compiler_version), ...
    'shape:production:CompilerMismatch','Compiler/runtime identity differs from the receipt.');
assert(strcmpi(q.scientific_release_authority,spec.scientific_release_authority) && ...
    strcmpi(q.binding_sha256,spec.binding_sha), ...
    'shape:production:ScientificAuthority','Receipt scientific/binding authority mismatch.');
assert(logical(q.protected_authorities_all_match) && ...
    environment.protected_authorities.all_match, ...
    'shape:production:ProtectedHashMismatch','Protected authority verification failed.');
assert(logical(q.observer_mex_selftest_pass) && environment.observer_mex_selftest.pass && ...
    strcmpi(q.observer_mex_sha256,environment.observer_mex_selftest.mex_sha256) && ...
    strcmpi(q.observer_source_sha256,environment.observer_mex_selftest.source_sha256), ...
    'shape:production:ObserverAuthority','Observer MEX provenance differs from the receipt.');
assert(logical(q.cache_isolation_pass) && logical(q.physical_qualification_pass) && ...
    logical(q.filegen_readback_pass) && ~logical(q.repository_root_slprj_used) && ...
    double(q.physical_runs_attempted)==96 && double(q.physical_runs_completed)==96 && ...
    double(q.scientific_validator_passes)==96 && double(q.eof_warning_count)==0 && ...
    double(q.retries)==0 && double(q.quarantines)==0 && double(q.failures)==0, ...
    'shape:production:ConcurrencyEvidence','Required cache-isolation physical evidence is incomplete.');
population=q.physical_population;
assert(strcmp(population.authority,'PILOT24_P6_NON_E2B_24X4') && ...
    isequal(double(population.parent_ids(:)'),9001:9024) && ...
    double(population.siblings_per_parent)==4 && double(population.run_count)==96, ...
    'shape:production:ConcurrencyPopulation', ...
    'Receipt physical qualification population differs from the frozen 24x4 authority.');
assert(double(environment.process_cluster_capacity)>=double(requested_workers), ...
    'shape:production:InsufficientCapacity','Current host capacity is below qualified concurrency.');
report=struct('path',path,'sha256',shape.sha256_file(path),'status',q.status, ...
    'hostname',q.hostname,'host_fingerprint_sha256',q.host_identity.fingerprint_sha256, ...
    'qualified_workers',double(q.qualified_workers),'worker_profile',q.worker_profile, ...
    'evidence_receipt_path',q.evidence_receipt_path, ...
    'evidence_receipt_sha256',q.evidence_receipt_sha256,'accepted',true);
end
