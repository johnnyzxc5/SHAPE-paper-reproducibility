function result = qualify_parent(record,models,registry_dir,cfg)
%QUALIFY_PARENT Deterministically generate, qualify and freeze one parent.
started=datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSSXXX');
timer=tic; [ref,q]=shape.generate_reference(record,models,cfg); elapsed=toc(timer);
contract=shape.trajectory_contract(models,cfg);
id=double(record.parent_trajectory_id);
receipt=struct('schema_version','shape-trajectory-qualification-receipt-v2', ...
    'parent_trajectory_id',id,'trajectory_seed',double(record.trajectory_seed), ...
    'qualification_status',char(q.qualification_status),'accepted_attempt',q.accepted_attempt, ...
    'attempt_count',q.attempt_count,'failure_counts',q.failure_counts, ...
    'K_segments',double(record.K_segments),'trajectory_mode',char(string(record.trajectory_mode)), ...
    'metrics',q.metrics,'generator_sha256',contract.generator_sha256, ...
    'generator_source_files',{cellstr(contract.generator_source_files)}, ...
    'generator_source_hashes',{cellstr(contract.generator_source_hashes)}, ...
    'constraint_contract_sha256',contract.constraint_sha256,'model_sha256',contract.model_sha256, ...
    'timestamp_utc',char(started),'qualification_time_s',elapsed, ...
    'software_version',version,'software_release',version('-release'));
artifact_path=''; receipt_path=fullfile(registry_dir,sprintf('parent_%04d_qualification.json',id));
trajectory_sha256='';
if q.qualification_status=="PASS"
    artifact=struct('schema_version',contract.schema_version,'parent_trajectory_id',id, ...
        'trajectory_seed',double(record.trajectory_seed),'K_segments',double(record.K_segments), ...
        'trajectory_mode',char(string(record.trajectory_mode)),'rng_algorithm',contract.rng_algorithm, ...
        'rng_version',contract.rng_version,'reference',ref,'qualification',q, ...
        'generator_sha256',contract.generator_sha256, ...
        'constraint_contract_sha256',contract.constraint_sha256,'model_sha256',contract.model_sha256, ...
        'software_version',version,'software_release',version('-release'));
    artifact.generator_source_files=contract.generator_source_files;
    artifact.generator_source_hashes=contract.generator_source_hashes;
    artifact.constraint_canonical_json=contract.constraint_canonical_json;
    artifact.trajectory_sha256=shape.trajectory_content_hash(artifact);
    trajectory_sha256=artifact.trajectory_sha256; receipt.trajectory_sha256=trajectory_sha256;
    [artifact_path,receipt_path]=shape.save_frozen_trajectory(registry_dir,artifact,receipt);
else
    receipt.trajectory_sha256=''; shape.write_json_atomic(receipt_path,receipt);
end
result=struct('parent_trajectory_id',id,'qualification_status',char(q.qualification_status), ...
    'accepted_attempt',q.accepted_attempt,'attempt_count',q.attempt_count, ...
    'failure_counts',q.failure_counts,'metrics',q.metrics,'trajectory_sha256',trajectory_sha256, ...
    'generator_sha256',contract.generator_sha256,'constraint_contract_sha256',contract.constraint_sha256, ...
    'model_sha256',contract.model_sha256,'artifact_path',artifact_path,'receipt_path',receipt_path, ...
    'qualification_time_s',elapsed,'K_segments',double(record.K_segments), ...
    'trajectory_mode',char(string(record.trajectory_mode)),'trajectory_seed',double(record.trajectory_seed));
end
