function contract = trajectory_contract(models,cfg)
%TRAJECTORY_CONTRACT Versioned identifiers for generator, constraints and model.
code_dir=fileparts(fileparts(mfilename('fullpath')));
source_files={fullfile(code_dir,'GenerarTrayectoriaAleatoriaSegura_MR.m'), ...
    fullfile(code_dir,'inverse_dynamics_kinova_MR.m'),fullfile(code_dir,'get_Friction_Nominal.m'), ...
    fullfile(code_dir,'+shape','generate_reference.m'), ...
    fullfile(code_dir,'+shape','truncated_reachable_box_sample.m'), ...
    fullfile(code_dir,'+shape','trajectory_contract.m')};
source_hashes=strings(size(source_files));
for k=1:numel(source_files), source_hashes(k)=shape.sha256_file(source_files{k}); end
contract.generator_source_files=string(source_files);
contract.generator_source_hashes=source_hashes;
contract.generator_sha256=shape.sha256_canonical("SHAPE_SEQUENTIAL_GENERATOR_V2",strjoin(source_hashes,"|"));
limits=struct('q_min',[-pi;-2.25;-2.58;-pi;-2.10;-pi]*0.9, ...
    'q_max',[pi;2.25;2.58;pi;2.10;pi]*0.9,'dq',cfg.dq_max*0.85, ...
    'ddq',[5.2;5.2;5.2;10;10;10]*0.85,'tau',cfg.tau_max*0.85);
canonical=struct('schema','shape-trajectory-constraint-v1','duration_s',10.0, ...
    'fs_hz',1000,'n_time',10001,'max_attempts',500,'K',[2 3], ...
    'modes',{{'fly','stop'}},'limits',limits,'static_headroom',0.95, ...
    'proposal_headroom',0.92,'fly_tangent_limit_fraction',0.65, ...
    'observability','trapz(t,abs(dq_ref(2,:))) >= 0.8 rad', ...
    'final_predicates',{{'FINITE','GRID','Q_LIMIT','DQ_LIMIT','DDQ_LIMIT','TORQUE_LIMIT','OBSERVABILITY'}});
contract.constraint_canonical_json=jsonencode(canonical);
contract.constraint_sha256=shape.sha256_canonical("SHAPE_CONSTRAINT_CONTRACT_V1",contract.constraint_canonical_json);
contract.model_sha256=char(string(models.nominal_sha256));
contract.model_path=char(string(models.nominal_path));
contract.rng_algorithm='MATLAB RandStream mt19937ar';
contract.rng_version='MATLAB implementation associated with recorded software release';
contract.schema_version='shape-frozen-trajectory-v2';
end
