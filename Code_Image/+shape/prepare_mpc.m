function prep = prepare_mpc(t,q,dq,ddq)
%PREPARE_MPC Build the 50-ms controller reference without altering telemetry.
Ts = 0.05; stride = round(Ts/(t(2)-t(1)));
idx = 1:stride:numel(t);
if idx(end)~=numel(t), idx(end+1)=numel(t); end
q=q(:,idx); dq=dq(:,idx); ddq=ddq(:,idx); tc=t(idx);
ny=6; nu=6; nx=12;
Ac=[zeros(ny),eye(ny);zeros(ny,nx)]; Bc=[zeros(ny,nu);eye(nu)];
E=expm([Ac,Bc;zeros(nu,nx+nu)]*Ts);
prep=struct('Ts',Ts,'N',numel(tc),'nu',nu,'ny',ny,'nq',6, ...
 'Adseq',E(1:nx,1:nx),'Bdseq',E(1:nx,nx+1:end), ...
 'Cdseq',[eye(ny),zeros(ny)],'xop',[q;dq],'yop',q,'uop',ddq, ...
 'y_ref',q,'t',tc,'P2ExactCacheEnabled',true, ...
 'P2ExactCacheVersion','p2-exact-invariants-v1', ...
 'P3SharedRNEAEnabled',false,'P3SharedRNEAVersion','p3-shared-rnea-v1', ...
 'P4BMassBackend',0);
end
