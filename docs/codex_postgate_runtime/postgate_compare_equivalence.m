function out = postgate_compare_equivalence(res_normal, res_accel, spec, models, cfg)
%POSTGATE_COMPARE_EQUIVALENCE Dual-layer equivalence validator: raw double in-memory + canonical HDF5 delivery.
% Enforces exact project authority:
%   1. Level 1A: In-memory canonical-precision pre-serialization arrays (fresh Normal vs fresh Accelerator)
%      - Fresh Normal vs fresh Accelerator GMO evaluated under existing P4C numerical authority.
%   2. Level 1B: Fresh delivery HDF5 comparison (fresh Normal vs fresh Accelerator)
%   3. Level 2: Historical Pilot V2 GOLD HDF5 delivery-level check:
%      - 22 backend-independent datasets verified strict bitwise exact.
%      - Historical Pilot GOLD vs fresh MEX GMO = INFORMATIONAL_ONLY_NOT_GATE (Blocker 5).
%      - Downstream GMO CWT representations (/cwt/gmo_log, /cwt/gmo_magnitude) gated by ratified P1B M03 float32-spacing guard (<= 32 spacings).
%      - Live same-input GOLD/MEX co-replay is NOT executed by this harness.
%   4. Authoritative Observer Provenance Gating (finite_difference_batch_mex, MEX_ACTIVE, zero fallback, verified hashes)
%   5. Effective Execution Configuration Gating (ode45, RelTol, AbsTol, MaxStep, SampleTime = -1)
%   6. Instrumentation Validity Gating (positive counters required before parity comparison)

raw_names = {'q', 'dq', 'tau_cmd', 'shape', 'torque', 'eo', 'q_ref', 'dq_ref', 'ddq_ref', 'tau_nom', 'timebase'};
gmo_authority_max_abs = 2^-28;
gmo_authority_rmse = 5.25072422013466e-11;

% =========================================================================
% LEVEL 1A: IN-MEMORY CANONICAL-PRECISION EQUIVALENCE (Fresh Normal vs Fresh Accel)
% Detects execution drift prior to float32 HDF5 serialization quantization
% =========================================================================
raw_norm = res_normal.in_memory_arrays;
raw_acc = res_accel.in_memory_arrays;

raw_metrics = struct();
for k = 1:numel(raw_names)
    n_val = raw_norm.(raw_names{k});
    a_val = raw_acc.(raw_names{k});
    raw_metrics.(raw_names{k}) = local_array_metric(n_val, a_val);
end

raw_direct_bitwise_pass = all(structfun(@(x) logical(x.bitwise_equal), raw_metrics));

% GMO backend-aware check on in-memory normalized GMO under P4C authority
raw_gmo_metric = local_array_metric(raw_norm.normed_gmo, raw_acc.normed_gmo);
raw_gmo_pass = (raw_gmo_metric.max_abs <= gmo_authority_max_abs) && ...
               (raw_gmo_metric.rmse <= gmo_authority_rmse);
raw_gmo_metric.authority_max_abs = gmo_authority_max_abs;
raw_gmo_metric.authority_rmse = gmo_authority_rmse;
raw_gmo_metric.pass = raw_gmo_pass;

level1a_in_memory_gate = struct('pass', raw_direct_bitwise_pass && raw_gmo_pass, ...
    'direct_bitwise_pass', raw_direct_bitwise_pass, ...
    'gmo_pass', raw_gmo_pass, ...
    'signals', raw_metrics, ...
    'gmo', raw_gmo_metric);

% =========================================================================
% LEVEL 1B: FRESH DELIVERY HDF5 EQUIVALENCE (Fresh Normal HDF5 vs Fresh Accel HDF5)
% Compares all 25 scientific datasets written by serialize_run.m and immutable root attributes.
% =========================================================================
norm_path = res_normal.path;
accel_path = res_accel.path;

all_25_datasets = { ...
    '/temporal/shape', ...
    '/temporal/torque', ...
    '/temporal/gmo', ...
    '/temporal/energy', ...
    '/cwt/shape_log', ...
    '/cwt/torque_log', ...
    '/cwt/gmo_log', ...
    '/cwt/energy_log', ...
    '/cwt/shape_magnitude', ...
    '/cwt/torque_magnitude', ...
    '/cwt/gmo_magnitude', ...
    '/cwt/energy_magnitude', ...
    '/views/shape_fft_amplitude', ...
    '/coordinates/fft_frequency_hz', ...
    '/coordinates/cwt_frequency_hz', ...
    '/coordinates/cwt_time_s', ...
    '/coordinates/telemetry_time_s', ...
    '/quality/coi_valid_mask', ...
    '/telemetry/q_meas', ...
    '/telemetry/dq_meas', ...
    '/telemetry/tau_cmd', ...
    '/reference/q_ref', ...
    '/reference/dq_ref', ...
    '/reference/ddq_ref', ...
    '/reference/tau_nom' ...
};

fresh_delivery_datasets_non_temporal_gmo = all_25_datasets(~strcmp(all_25_datasets, '/temporal/gmo'));

fresh_delivery_metrics = struct();
for k = 1:numel(fresh_delivery_datasets_non_temporal_gmo)
    dset_path = fresh_delivery_datasets_non_temporal_gmo{k};
    norm_data = h5read(norm_path, dset_path);
    accel_data = h5read(accel_path, dset_path);
    field_name = local_safe_field(dset_path);
    fresh_delivery_metrics.(field_name) = local_array_metric(norm_data, accel_data);
end

fresh_delivery_bitwise_pass = all(structfun(@(x) logical(x.bitwise_equal), fresh_delivery_metrics));

% Fresh delivery GMO comparison under P4C authority
norm_gmo_h5 = h5read(norm_path, '/temporal/gmo');
accel_gmo_h5 = h5read(accel_path, '/temporal/gmo');
fresh_gmo_metric = local_array_metric(norm_gmo_h5, accel_gmo_h5);
fresh_gmo_pass = (fresh_gmo_metric.max_abs <= gmo_authority_max_abs) && ...
                 (fresh_gmo_metric.rmse <= gmo_authority_rmse);
fresh_gmo_metric.authority_max_abs = gmo_authority_max_abs;
fresh_gmo_metric.authority_rmse = gmo_authority_rmse;
fresh_gmo_metric.pass = fresh_gmo_pass;

% Root immutable attribute comparison
immutable_attributes = { ...
    'run_uid', ...
    'parent_trajectory_id', ...
    'fault_class', ...
    'schema_version', ...
    'normalization', ...
    'rng_provenance', ...
    'manifest_record_json', ...
    'software_provenance', ...
    'code_state_id', ...
    'input_manifest_sha256', ...
    'input_manifest_path', ...
    'trajectory_sha256', ...
    'trajectory_binding_sha256', ...
    'generator_sha256', ...
    'constraint_contract_sha256', ...
    'trajectory_model_sha256', ...
    'trajectory_K_segments', ...
    'trajectory_mode', ...
    'solver', ...
    'solver_rel_tol', ...
    'solver_abs_tol', ...
    'solver_max_step', ...
    'telemetry_dt_s', ...
    'observer_ctdq_backend', ...
    'observer_ctdq_backend_version', ...
    'observer_ctdq_requested_backend_version', ...
    'observer_ctdq_actual_backend_version', ...
    'observer_ctdq_source_version', ...
    'observer_ctdq_status', ...
    'observer_ctdq_fallback_used', ...
    'observer_ctdq_fallback_status', ...
    'observer_ctdq_fallback_reason', ...
    'observer_ctdq_selftest_status', ...
    'observer_ctdq_mex_sha256', ...
    'observer_ctdq_source_sha256', ...
    'qc_state', ...
    'e4_calibration_state', ...
    'e4_calibration_source', ...
    'e4_pooled_velocity_rms_json' ...
};

% Enforce exact 40-root-attribute serializer contract (39 immutable + 1 dynamic profile_json)
expected_root_attributes = [immutable_attributes, {'profile_json'}];

try
    norm_info = h5info(norm_path, '/');
    if isempty(norm_info.Attributes)
        norm_root_names = {};
    else
        norm_root_names = {norm_info.Attributes.Name};
    end
catch
    norm_root_names = {};
end

try
    accel_info = h5info(accel_path, '/');
    if isempty(accel_info.Attributes)
        accel_root_names = {};
    else
        accel_root_names = {accel_info.Attributes.Name};
    end
catch
    accel_root_names = {};
end

% A & B. Root inventory completeness and exactness (40 attributes required)
missing_normal_attributes = setdiff(expected_root_attributes, norm_root_names);
missing_accelerator_attributes = setdiff(expected_root_attributes, accel_root_names);
unexpected_normal_attributes = setdiff(norm_root_names, expected_root_attributes);
unexpected_accelerator_attributes = setdiff(accel_root_names, expected_root_attributes);

final_attribute_inventory_pass = isempty(missing_normal_attributes) && ...
    isempty(missing_accelerator_attributes) && ...
    isempty(unexpected_normal_attributes) && ...
    isempty(unexpected_accelerator_attributes) && ...
    (numel(norm_root_names) == 40) && ...
    (numel(accel_root_names) == 40);

% Check existence and exact value equality for all 39 immutable attributes
immutable_normal_present_count = sum(ismember(immutable_attributes, norm_root_names));
immutable_accelerator_present_count = sum(ismember(immutable_attributes, accel_root_names));

attr_results = struct();
attr_match_all = true;
immutable_compared_count = 0;

for a_idx = 1:numel(immutable_attributes)
    att_name = immutable_attributes{a_idx};
    has_norm = any(strcmp(norm_root_names, att_name));
    has_accel = any(strcmp(accel_root_names, att_name));
    
    if ~has_norm || ~has_accel
        % Missing in either file is immediate fail; missing in both is immediate fail
        attr_results.(att_name) = struct( ...
            'present_normal', has_norm, ...
            'present_accelerator', has_accel, ...
            'equal', false, ...
            'status', 'MISSING_REQUIRED_ATTRIBUTE');
        attr_match_all = false;
    else
        v_norm = h5readatt(norm_path, '/', att_name);
        v_accel = h5readatt(accel_path, '/', att_name);
        eq = isequal(v_norm, v_accel);
        attr_results.(att_name) = struct( ...
            'present_normal', true, ...
            'present_accelerator', true, ...
            'equal', eq, ...
            'status', 'COMPARED');
        immutable_compared_count = immutable_compared_count + 1;
        if ~eq
            attr_match_all = false;
        end
    end
end

final_immutable_attribute_equality_pass = attr_match_all && ...
    (immutable_compared_count == numel(immutable_attributes)) && ...
    (immutable_normal_present_count == numel(immutable_attributes)) && ...
    (immutable_accelerator_present_count == numel(immutable_attributes));

has_norm_profile = any(strcmp(norm_root_names, 'profile_json'));
has_accel_profile = any(strcmp(accel_root_names, 'profile_json'));

excluded_dynamic_attributes = struct( ...
    'attribute_name', 'profile_json', ...
    'present_in_normal', has_norm_profile, ...
    'present_in_accelerator', has_accel_profile, ...
    'rationale', 'profile_json is required to exist in both files per the 40-attribute serializer contract, but is excluded from exact value equality because it records dynamic runtime telemetry including execution walltimes (simulink_wall_s, residuals_s, cwt_rebin_s, etc.), compile timing, CPU profiler snapshots, and runtime-specific diagnostics that differ naturally between runs and backend modes by design.');

level1b_fresh_delivery_gate = struct( ...
    'pass', fresh_delivery_bitwise_pass && fresh_gmo_pass && final_attribute_inventory_pass && final_immutable_attribute_equality_pass, ...
    'expected_dataset_count', 25, ...
    'compared_dataset_count', 25, ...
    'datasets_checked', {all_25_datasets}, ...
    'non_gmo_dataset_count', 24, ...
    'bitwise_pass', fresh_delivery_bitwise_pass, ...
    'gmo_pass', fresh_gmo_pass, ...
    'signals', fresh_delivery_metrics, ...
    'gmo', fresh_gmo_metric, ...
    'expected_root_attribute_count', 40, ...
    'observed_normal_root_attribute_count', numel(norm_root_names), ...
    'observed_accelerator_root_attribute_count', numel(accel_root_names), ...
    'immutable_expected_count', numel(immutable_attributes), ...
    'immutable_normal_present_count', immutable_normal_present_count, ...
    'immutable_accelerator_present_count', immutable_accelerator_present_count, ...
    'immutable_compared_count', immutable_compared_count, ...
    'excluded_dynamic_attribute_count', 1, ...
    'excluded_dynamic_attribute_list', {{'profile_json'}}, ...
    'missing_normal_attributes', {missing_normal_attributes}, ...
    'missing_accelerator_attributes', {missing_accelerator_attributes}, ...
    'unexpected_normal_attributes', {unexpected_normal_attributes}, ...
    'unexpected_accelerator_attributes', {unexpected_accelerator_attributes}, ...
    'final_attribute_inventory_pass', final_attribute_inventory_pass, ...
    'final_immutable_attribute_equality_pass', final_immutable_attribute_equality_pass, ...
    'immutable_attributes_checked', {immutable_attributes}, ...
    'attribute_details', attr_results, ...
    'excluded_dynamic_attributes', excluded_dynamic_attributes);

% =========================================================================
% LEVEL 2: HISTORICAL CANONICAL REFERENCE HDF5 CHECK (Pilot V2 GOLD Check)
% Serves as immutable third delivery check across all 25 scientific datasets.
% Partition:
%   1. 22 strict backend-independent datasets -> strict bitwise equality against GOLD
%   2. 1 temporal GMO dataset (/temporal/gmo) -> INFORMATIONAL_ONLY_NOT_GATE (Blocker 5)
%   3. 2 GMO CWT representations (/cwt/gmo_log, /cwt/gmo_magnitude) -> P1B M03 numerical guard (<= 32 float32 spacings)
% =========================================================================
ref_path = spec.reference_path;

% Explicit 25-dataset partition for Level 2 Historical GOLD comparison
hist_temporal_gmo_dataset = {'/temporal/gmo'};
hist_gmo_cwt_datasets = {'/cwt/gmo_log', '/cwt/gmo_magnitude'};
hist_strict_bitwise_datasets = all_25_datasets( ...
    ~ismember(all_25_datasets, [hist_temporal_gmo_dataset, hist_gmo_cwt_datasets]));

assert(numel(hist_strict_bitwise_datasets) == 22, ...
    'Historical strict-bitwise set must contain exactly 22 backend-independent datasets');
assert(numel(hist_temporal_gmo_dataset) == 1, ...
    'Historical temporal GMO set must contain exactly 1 dataset');
assert(numel(hist_gmo_cwt_datasets) == 2, ...
    'Historical GMO CWT representation set must contain exactly 2 datasets');

% 1. Evaluate 22 strict backend-independent datasets against historical GOLD
hist_delivery_metrics = struct();
hist_failing_strict_datasets = {};
for k = 1:numel(hist_strict_bitwise_datasets)
    dset_path = hist_strict_bitwise_datasets{k};
    ref_data = h5read(ref_path, dset_path);
    accel_data = h5read(accel_path, dset_path);
    field_name = local_safe_field(dset_path);
    m = local_array_metric(ref_data, accel_data);
    hist_delivery_metrics.(field_name) = m;
    if ~m.bitwise_equal
        hist_failing_strict_datasets{end+1} = dset_path; %#ok<AGROW>
    end
end
strict_bitwise_22_pass = isempty(hist_failing_strict_datasets);

% 2. Evaluate 2 GMO CWT downstream representations under ratified P1B M03 guard (<= 32 float32 spacings)
p1b_guard_threshold = 32;
hist_gmo_cwt_metrics = struct();
hist_failing_gmo_cwt_datasets = {};
for k = 1:numel(hist_gmo_cwt_datasets)
    dset_path = hist_gmo_cwt_datasets{k};
    ref_data = h5read(ref_path, dset_path);
    accel_data = h5read(accel_path, dset_path);
    field_name = local_safe_field(dset_path);
    rep_m = local_p1b_repr_metric(ref_data, accel_data, p1b_guard_threshold);
    hist_gmo_cwt_metrics.(field_name) = rep_m;
    if ~rep_m.pass
        hist_failing_gmo_cwt_datasets{end+1} = dset_path; %#ok<AGROW>
    end
end
gmo_cwt_p1b_representation_pass = isempty(hist_failing_gmo_cwt_datasets);

% 3. Stored historical Pilot GOLD GMO vs current MEX GMO is INFORMATIONAL ONLY (Blocker 5)
ref_gmo_h5 = h5read(ref_path, '/temporal/gmo');
hist_gmo_m = local_array_metric(ref_gmo_h5, accel_gmo_h5);
hist_gmo_informational = struct('bitwise_equal', hist_gmo_m.bitwise_equal, ...
    'max_abs', hist_gmo_m.max_abs, 'rmse', hist_gmo_m.rmse, ...
    'authority_max_abs', gmo_authority_max_abs, 'authority_rmse', gmo_authority_rmse, ...
    'status', 'INFORMATIONAL_ONLY_NOT_GATE', ...
    'backend_note', 'Historical GOLD used finite_difference_gold; candidate uses finite_difference_batch_mex. Live same-input GOLD/MEX co-replay is NOT executed by this harness.');

% Identity and solver metadata checks on HDF5
binding_expected = 'e51122549278d5ae2597605bbeaa75f4f4fff1e244657dad399a2428d85e15ef';
identity = struct( ...
    'canonical_ref_sha256_match', strcmpi(char(shape.sha256_file(ref_path)), spec.reference_sha256), ...
    'uid', strcmp(char(string(h5readatt(accel_path, '/', 'run_uid'))), spec.uid), ...
    'parent', double(h5readatt(accel_path, '/', 'parent_trajectory_id')) == spec.parent, ...
    'fault', strcmpi(char(string(h5readatt(accel_path, '/', 'fault_class'))), spec.fault), ...
    'mode', strcmpi(char(string(h5readatt(accel_path, '/', 'trajectory_mode'))), spec.mode), ...
    'K', double(h5readatt(accel_path, '/', 'trajectory_K_segments')) == spec.K, ...
    'trajectory_sha256', strcmpi(char(string(h5readatt(accel_path, '/', 'trajectory_sha256'))), spec.trajectory_sha256), ...
    'binding_sha256', strcmpi(char(string(h5readatt(accel_path, '/', 'trajectory_binding_sha256'))), binding_expected), ...
    'solver', strcmp(char(string(h5readatt(accel_path, '/', 'solver'))), 'ode45'), ...
    'RelTol', double(h5readatt(accel_path, '/', 'solver_rel_tol')) == 1e-6, ...
    'AbsTol', double(h5readatt(accel_path, '/', 'solver_abs_tol')) == 1e-8, ...
    'MaxStep', str2double(string(h5readatt(accel_path, '/', 'solver_max_step'))) == 1e-3);

identity_pass = all(structfun(@(x) logical(x), identity));

% Level 2 Historical Gate Pass Condition
level2_pass = strict_bitwise_22_pass && identity_pass && gmo_cwt_p1b_representation_pass;

level2_historical_gate = struct( ...
    'pass', level2_pass, ...
    'expected_dataset_count', 25, ...
    'compared_dataset_count', 25, ...
    'datasets_checked', {all_25_datasets}, ...
    'strict_bitwise_datasets_checked', {hist_strict_bitwise_datasets}, ...
    'strict_bitwise_dataset_count', numel(hist_strict_bitwise_datasets), ...
    'strict_bitwise_pass', strict_bitwise_22_pass, ...
    'strict_bitwise_failing_datasets', {hist_failing_strict_datasets}, ...
    'bitwise_pass', strict_bitwise_22_pass, ...
    'identity_pass', identity_pass, ...
    'gmo_cwt_p1b_representation_pass', gmo_cwt_p1b_representation_pass, ...
    'signals', hist_delivery_metrics, ...
    'gmo_informational', hist_gmo_informational, ...
    'gmo_cwt_representation', struct( ...
        'datasets_checked', {hist_gmo_cwt_datasets}, ...
        'guard_threshold', p1b_guard_threshold, ...
        'pass', gmo_cwt_p1b_representation_pass, ...
        'failing_datasets', {hist_failing_gmo_cwt_datasets}, ...
        'cwt_gmo_log', hist_gmo_cwt_metrics.cwt_gmo_log, ...
        'cwt_gmo_magnitude', hist_gmo_cwt_metrics.cwt_gmo_magnitude), ...
    'identity', identity);

% =========================================================================
% LEVEL 3: AUTHORITATIVE OBSERVER PROVENANCE GATE (Blockers 5 & 6)
% =========================================================================
norm_obs = res_normal.obs_provenance_check;
acc_obs = res_accel.obs_provenance_check;
observer_gate_pass = norm_obs.all_valid && acc_obs.all_valid;
observer_gate = struct( ...
    'pass', observer_gate_pass, ...
    'normal_provenance', norm_obs, ...
    'accelerator_provenance', acc_obs);

% =========================================================================
% LEVEL 4: EFFECTIVE EXECUTION CONFIGURATION GATE (Blocker 2)
% =========================================================================
norm_cfg = res_normal.effective_cfg_check;
acc_cfg = res_accel.effective_cfg_check;
effective_cfg_gate_pass = norm_cfg.all_valid && acc_cfg.all_valid;
effective_cfg_gate = struct( ...
    'pass', effective_cfg_gate_pass, ...
    'normal_effective_cfg', norm_cfg, ...
    'accelerator_effective_cfg', acc_cfg);

% =========================================================================
% LEVEL 5: INSTRUMENTATION VALIDITY & CALL TOPOLOGY GATE (Important 2)
% =========================================================================
topology = local_count_analysis(res_normal, res_accel, spec);

% =========================================================================
% OVERALL RESOLUTION
% =========================================================================
overall_pass = level1a_in_memory_gate.pass && ...
    level1b_fresh_delivery_gate.pass && ...
    level2_historical_gate.pass && ...
    observer_gate.pass && ...
    effective_cfg_gate.pass && ...
    topology.instrumentation_valid && ...
    topology.counts_match_exactly;

out = struct('pass', overall_pass, ...
    'production_authorized', false, ...
    'level1a_in_memory_gate', level1a_in_memory_gate, ...
    'level1b_fresh_delivery_gate', level1b_fresh_delivery_gate, ...
    'level2_historical_gate', level2_historical_gate, ...
    'observer_gate', observer_gate, ...
    'effective_cfg_gate', effective_cfg_gate, ...
    'topology', topology, ...
    'reference_sha256', spec.reference_sha256, ...
    'normal_hdf5_sha256', char(shape.sha256_file(norm_path)), ...
    'accelerator_hdf5_sha256', char(shape.sha256_file(accel_path)), ...
    'qualification_label', 'FAIL');

if overall_pass
    out.qualification_label = 'PASS_BACKEND_HARMONIZED';
elseif ~effective_cfg_gate.pass
    out.qualification_label = 'EFFECTIVE_CONFIGURATION_MISMATCH';
elseif ~observer_gate.pass
    out.qualification_label = 'OBSERVER_PROVENANCE_FAIL';
elseif ~topology.instrumentation_valid
    out.qualification_label = 'INSTRUMENTATION_INVALID';
elseif ~level1a_in_memory_gate.direct_bitwise_pass
    out.qualification_label = 'RAW_IN_MEMORY_SCIENTIFIC_REGRESSION';
elseif ~level1b_fresh_delivery_gate.bitwise_pass
    out.qualification_label = 'FRESH_DELIVERY_HDF5_SCIENTIFIC_REGRESSION';
elseif ~level1b_fresh_delivery_gate.final_attribute_inventory_pass
    out.qualification_label = 'FRESH_DELIVERY_HDF5_ATTRIBUTE_INVENTORY_MISMATCH';
elseif ~level1b_fresh_delivery_gate.final_immutable_attribute_equality_pass
    out.qualification_label = 'FRESH_DELIVERY_HDF5_ATTRIBUTE_MISMATCH';
elseif ~level1a_in_memory_gate.gmo_pass || ~level1b_fresh_delivery_gate.gmo_pass
    out.qualification_label = 'GMO_AUTHORITY_FAIL';
elseif ~topology.counts_match_exactly
    out.qualification_label = 'TOPOLOGY_OR_STEP_DRIFT_DETECTED';
elseif ~level2_historical_gate.identity_pass || ~level2_historical_gate.strict_bitwise_pass
    out.qualification_label = 'HISTORICAL_PROVENANCE_FAIL';
elseif ~level2_historical_gate.gmo_cwt_p1b_representation_pass
    out.qualification_label = 'HISTORICAL_GMO_REPRESENTATION_GUARD_FAIL';
else
    out.qualification_label = 'HISTORICAL_PROVENANCE_FAIL';
end

end

function m = local_array_metric(a, b)
class_equal = strcmp(class(a), class(b));
shape_equal = isequal(size(a), size(b));
if ~class_equal || ~shape_equal
    m = struct('class_equal', class_equal, 'shape_equal', shape_equal, 'bitwise_equal', false, ...
        'non_bitwise_scalar_count', max(numel(a), numel(b)), ...
        'total_scalar_count', max(numel(a), numel(b)), 'max_abs', NaN, 'rmse', NaN, 'max_ulp', NaN);
    return;
end
av = a(:); bv = b(:);
try
    ba = local_bits(av); bb = local_bits(bv);
catch
    m = struct('class_equal', class_equal, 'shape_equal', shape_equal, 'bitwise_equal', false, ...
        'non_bitwise_scalar_count', numel(av), ...
        'total_scalar_count', numel(av), 'max_abs', NaN, 'rmse', NaN, 'max_ulp', NaN);
    return;
end
neq = ba ~= bb;
d = double(bv) - double(av);
ulp = local_ulp(ba, bb);
if isempty(d)
    max_abs = 0; rmse = 0; max_ulp = 0;
else
    max_abs = max(abs(d)); rmse = sqrt(mean(d.^2)); max_ulp = double(max(ulp));
end
m = struct('class_equal', true, 'shape_equal', true, 'bitwise_equal', ~any(neq), ...
    'non_bitwise_scalar_count', sum(neq), 'total_scalar_count', numel(av), ...
    'max_abs', max_abs, 'rmse', rmse, 'max_ulp', max_ulp);
end

function bits = local_bits(value)
if isa(value, 'single')
    bits = typecast(value, 'uint32');
elseif isa(value, 'double')
    bits = typecast(value, 'uint64');
elseif isa(value, 'logical')
    bits = uint8(value);
elseif isinteger(value)
    bits = value;
else
    error('postgate:unsupported_class', 'Unsupported class for bitwise comparison: %s', class(value));
end
end

function d = local_ulp(a, b)
if isa(a, 'uint32')
    mask = bitshift(uint32(1), 31);
elseif isa(a, 'uint64')
    mask = bitshift(uint64(1), 63);
elseif isinteger(a) || islogical(a)
    d = abs(double(b) - double(a));
    return;
else
    d = zeros(size(a));
    return;
end
oa = a; ob = b;
na = bitand(a, mask) ~= 0; nb = bitand(b, mask) ~= 0;
oa(na) = bitcmp(a(na)); oa(~na) = bitxor(a(~na), mask);
ob(nb) = bitcmp(b(nb)); ob(~nb) = bitxor(b(~nb), mask);
d = max(oa, ob) - min(oa, ob);
end

function f = local_safe_field(path_str)
f = regexprep(path_str, '^/', '');
f = regexprep(f, '/', '_');
end

