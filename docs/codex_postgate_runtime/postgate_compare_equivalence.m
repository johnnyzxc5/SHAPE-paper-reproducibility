end


function top = local_count_analysis(res_normal, res_accel, spec)
top = struct();

% Validate instrumentation snapshots (Important 2: fail closed if missing or empty)
n_p0_valid = isfield(res_normal.profile, 'p0') && ~isempty(fieldnames(res_normal.profile.p0));
a_p0_valid = isfield(res_accel.profile, 'p0') && ~isempty(fieldnames(res_accel.profile.p0));

if ~n_p0_valid || ~a_p0_valid
    top.instrumentation_valid = false;
    top.instrumentation_reason = 'P0 profiler snapshot missing or empty';
    top.counts_match_exactly = false;
    top.step_drift_detected = true;
    return;
end

n_p0 = res_normal.profile.p0;
a_p0 = res_accel.profile.p0;

% Verify run_uid matches
uid_match = isfield(n_p0, 'run_uid') && isfield(a_p0, 'run_uid') && ...
    strcmp(char(string(n_p0.run_uid)), spec.uid) && ...
    strcmp(char(string(a_p0.run_uid)), spec.uid);

% Required counter fields must exist and be positive
req_fields = {'plant_rhs_entries', 'controller_entries', 'mpc_entries', 'quadprog_calls'};
fields_exist = all(isfield(n_p0, req_fields)) && all(isfield(a_p0, req_fields));

if ~uid_match || ~fields_exist
    top.instrumentation_valid = false;
    top.instrumentation_reason = 'Counter fields missing or run_uid mismatch';
    top.counts_match_exactly = false;
    top.step_drift_detected = true;
    return;
end

top.normal_counts = struct( ...
    'plant_rhs_entries', double(n_p0.plant_rhs_entries), ...
    'controller_entries', double(n_p0.controller_entries), ...
    'mpc_entries', double(n_p0.mpc_entries), ...
    'quadprog_calls', double(n_p0.quadprog_calls), ...
    'raw_tout_count', double(res_normal.raw_tout_count));

top.accelerator_counts = struct( ...
    'plant_rhs_entries', double(a_p0.plant_rhs_entries), ...
    'controller_entries', double(a_p0.controller_entries), ...
    'mpc_entries', double(a_p0.mpc_entries), ...
    'quadprog_calls', double(a_p0.quadprog_calls), ...
    'raw_tout_count', double(res_accel.raw_tout_count));

% Verify counters expected to be positive are strictly positive
counters_positive = (top.normal_counts.plant_rhs_entries > 0) && ...
    (top.normal_counts.controller_entries > 0) && ...
    (top.normal_counts.mpc_entries > 0) && ...
    (top.normal_counts.quadprog_calls > 0) && ...
    (top.normal_counts.raw_tout_count > 0) && ...
    (top.accelerator_counts.plant_rhs_entries > 0) && ...
    (top.accelerator_counts.controller_entries > 0) && ...
    (top.accelerator_counts.mpc_entries > 0) && ...
    (top.accelerator_counts.quadprog_calls > 0) && ...
    (top.accelerator_counts.raw_tout_count > 0);

if ~counters_positive
    top.instrumentation_valid = false;
    top.instrumentation_reason = 'Counters expected to be positive were zero or negative';
    top.counts_match_exactly = false;
    top.step_drift_detected = true;
    return;
end

top.instrumentation_valid = true;
top.instrumentation_reason = 'All required counters present, positive, and verified against run_uid';

top.delta_counts = struct( ...
    'plant_rhs_entries', top.accelerator_counts.plant_rhs_entries - top.normal_counts.plant_rhs_entries, ...
    'controller_entries', top.accelerator_counts.controller_entries - top.normal_counts.controller_entries, ...
    'mpc_entries', top.accelerator_counts.mpc_entries - top.normal_counts.mpc_entries, ...
    'quadprog_calls', top.accelerator_counts.quadprog_calls - top.normal_counts.quadprog_calls, ...
    'raw_tout_count', top.accelerator_counts.raw_tout_count - top.normal_counts.raw_tout_count);

counts_match = (top.delta_counts.plant_rhs_entries == 0) && ...
    (top.delta_counts.controller_entries == 0) && ...
    (top.delta_counts.mpc_entries == 0) && ...
    (top.delta_counts.quadprog_calls == 0) && ...
    (top.delta_counts.raw_tout_count == 0);

top.counts_match_exactly = counts_match;
top.step_drift_detected = ~counts_match;

end

function m = local_p1b_repr_metric(a, b, guard_threshold)
%LOCAL_P1B_REPR_METRIC Exact ratified P1B M03 downstream representation metric.
% Source authority: Code_Image/run_postpilot_p1b.m lines 285-289, 318-326.
% Metric: max(abs(double(b) - double(a)) ./ ulp_spacing, [], 'all')
% where: ulp_spacing = max(double(eps(single(max(abs(a), abs(b))))), double(eps(single(1))))
% Ratified guard: max_spacing <= 32 float32 spacings (float32_accumulation_guard_ulps).

if nargin < 3
    guard_threshold = 32;
end

class_equal = strcmp(class(a), class(b));
shape_equal = isequal(size(a), size(b));
if ~class_equal || ~shape_equal
    m = struct( ...
        'pass', false, ...
        'p1b_repr_metric', NaN, ...
        'p1b_repr_guard', guard_threshold, ...
        'p1b_repr_pass', false, ...
        'bitwise_equal', false, ...
        'max_abs', NaN, ...
        'rmse', NaN, ...
        'mae', NaN, ...
        'correlation', NaN, ...
        'diagnostic_ordered_bit_distance', NaN, ...
        'class_equal', class_equal, ...
        'shape_equal', shape_equal, ...
        'total_scalar_count', max(numel(a), numel(b)), ...
        'authority', 'P1B_M03_DOWNSTREAM_REPRESENTATION_GUARD');
    return;
end

da = double(a);
db = double(b);
diff_val = db - da;
abs_diff = abs(diff_val);

if isempty(diff_val)
    max_abs = 0;
    rmse = 0;
    mae = 0;
    corr_val = 1;
    max_spacing_ulp = 0;
    is_finite_all = true;
else
    max_abs = max(abs_diff(:));
    rmse = sqrt(mean(diff_val(:).^2));
    mae = mean(abs_diff(:));
    corr_val = local_flat_corr(da, db);
    
    % Exact P1B M03 float32-spacing metric (Code_Image/run_postpilot_p1b.m lines 285-289)
    env = max(abs(da), abs(db));
    ulp_spacing = max(double(eps(single(env))), double(eps(single(1))));
    spacing_ratio = abs_diff ./ ulp_spacing;
    max_spacing_ulp = max(spacing_ratio(:));
    is_finite_all = all(isfinite([max_abs, rmse, mae, max_spacing_ulp]));
end

p1b_pass = is_finite_all && (max_spacing_ulp <= guard_threshold);

% Also compute the ordered bit distance (diagnostic only, not gate authority)
diag_metric = local_array_metric(a, b);

m = struct( ...
    'pass', p1b_pass, ...
    'p1b_repr_metric', max_spacing_ulp, ...
    'p1b_repr_guard', guard_threshold, ...
    'p1b_repr_pass', p1b_pass, ...
    'bitwise_equal', isequal(a, b), ...
    'max_abs', max_abs, ...
    'rmse', rmse, ...
    'mae', mae, ...
    'correlation', corr_val, ...
    'diagnostic_ordered_bit_distance', diag_metric.max_ulp, ...
    'class_equal', class_equal, ...
    'shape_equal', shape_equal, ...
    'total_scalar_count', numel(da), ...
    'authority', 'P1B_M03_DOWNSTREAM_REPRESENTATION_GUARD');
end

function c = local_flat_corr(a, b)
% Replicates flat_corr from Code_Image/run_postpilot_p1b.m lines 291-295
av = a(:);
bv = b(:);
if isequal(av, bv)
    c = 1;
elseif std(av) == 0 || std(bv) == 0
    c = double(all(av == bv));
else
    R = corrcoef(av, bv);
    c = R(1, 2);
end
end
