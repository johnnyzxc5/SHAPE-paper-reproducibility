function receipt = postgate_isolate_session(model_name)
%POSTGATE_ISOLATE_SESSION Enforce strict fresh-run isolation before every physical simulation.
% Precedent: P4C-R3 (run_postpilot_p4c_r3.m lines 70-74) and simulate_run.m cleanup.
%
% Actions:
%   1. Force Fast Restart OFF on the model.
%   2. Verify the model is in 'stopped' status (no retained simulation state).
%   3. Reset host-side persistent MPC runtime context (shape.mpc_runtime_context).
%   4. Clear all persistent variables in plant, controller, kinematics, and bridge functions.
%   5. Reset P0 profiler memory.

if nargin < 1 || isempty(model_name)
    model_name = 'Kinova_Fault_Simulator';
end

receipt = struct('model_name', model_name, ...
    'fast_restart_forced_off', false, ...
    'simulation_status_stopped', false, ...
    'persistent_functions_cleared', false, ...
    'runtime_context_cleared', false, ...
    'isolation_verified', false, ...
    'precedent', 'P4C-R3 run_postpilot_p4c_r3.m lines 70-74 and simulate_run.m lines 11-13', ...
    'cleared_symbols', {{ ...
        'solve_flatness_mpc_step_MR', ...
        'solve_flatness_mpc_runtime_MR', ...
        'mpc_exact_invariants_MR', ...
        'rnea_shared_kinematics_MR', ...
        'InverseDynamicsSharedKinematics_MR', ...
        'MassMatrixSharedKinematics_MR', ...
        'MassMatrixZeroStateSharedKinematics_MR', ...
        'kinova_state_space_sucia_MR', ...
        'p0_profile_bridge' ...
    }});

% 1. Force Fast Restart OFF
if bdIsLoaded(model_name)
    try
        set_param(model_name, 'FastRestart', 'off');
        receipt.fast_restart_forced_off = strcmp(get_param(model_name, 'FastRestart'), 'off');
    catch
        receipt.fast_restart_forced_off = false;
    end
    sim_status = get_param(model_name, 'SimulationStatus');
    receipt.simulation_status_stopped = strcmp(sim_status, 'stopped');
else
    load_system(model_name);
    try
        set_param(model_name, 'FastRestart', 'off');
        receipt.fast_restart_forced_off = true;
    catch
        receipt.fast_restart_forced_off = false;
    end
    receipt.simulation_status_stopped = true;
end

% 2. Clear established persistent function states (P4C-R3 precedent)
clear solve_flatness_mpc_step_MR solve_flatness_mpc_runtime_MR ...
    mpc_exact_invariants_MR rnea_shared_kinematics_MR ...
    InverseDynamicsSharedKinematics_MR MassMatrixSharedKinematics_MR ...
    MassMatrixZeroStateSharedKinematics_MR kinova_state_space_sucia_MR ...
    p0_profile_bridge
receipt.persistent_functions_cleared = true;

% 3. Clear host runtime context
try
    shape.mpc_runtime_context('clear');
    ctx_check = shape.mpc_runtime_context('snapshot');
    receipt.runtime_context_cleared = ~ctx_check.initialized;
catch
    receipt.runtime_context_cleared = false;
end

receipt.isolation_verified = receipt.fast_restart_forced_off && ...
    receipt.simulation_status_stopped && ...
    receipt.persistent_functions_cleared && ...
    receipt.runtime_context_cleared;

end
