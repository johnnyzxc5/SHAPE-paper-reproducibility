function diag = postgate_unattributed_diagnostic(profile, telemetry, models, opt_prep)
%POSTGATE_UNATTRIBUTED_DIAGNOSTIC Forensic walltime attribution tool.
% Strictly separates in-simulation measurements from offline benchmarks.
%
% Receipt fields strictly distinguish:
%   - MEASURED_IN_SIMULATION: Direct timestamps captured during sim() execution
%   - OFFLINE_ESTIMATE: Isolated microbenchmarks extrapolated over entry counts
%   - CALCULATED_ESTIMATE: Residual after applying offline estimates
%
% Enforces Important 5: Preserves raw signed unattributed remainder (no max(0,...) clipping of authoritative field).
% Enforces Blocker 1: Uses in-simulation context benchmark or safe deterministic reinstall.

if nargin < 4, opt_prep = []; end

sim_wall_s = double(profile.simulink_wall_s);
warnings = {};

if isfield(profile, 'p0') && ~isempty(fieldnames(profile.p0))
    p0 = profile.p0;
    mpc_s = double(p0.mpc_total_s);
    plant_s = double(p0.plant_total_s);
    qp_s = double(p0.quadprog_total_s);
    n_entries = double(p0.controller_entries);
    
    % Measured Computed_Torque (Direct In-Simulation Timing)
    if isfield(p0, 'computed_torque_total_s')
        ct_s = double(p0.computed_torque_total_s);
        ct_entries = double(p0.computed_torque_entries);
        ct_mean_s = double(p0.computed_torque_mean_s);
    else
        ct_s = 0; ct_entries = 0; ct_mean_s = 0;
    end
    
    % Measured MPC Macro Decomposition Buckets
    if isfield(p0, 'mpc_state_cost_prep_s')
        mpc_state_cost_prep_s = double(p0.mpc_state_cost_prep_s);
        mpc_dynamics_constraint_s = double(p0.mpc_dynamics_constraint_s);
        mpc_postsolve_s = double(p0.mpc_postsolve_s);
    else
        mpc_state_cost_prep_s = double(p0.mpc_reference_build_s) + double(p0.mpc_prediction_build_s) + double(p0.mpc_cost_build_s);
        mpc_dynamics_constraint_s = double(p0.mpc_mass_matrix_s) + double(p0.mpc_inverse_dynamics_s) + double(p0.mpc_friction_s) + double(p0.mpc_constraint_build_s) + double(p0.mpc_bounds_build_s);
        mpc_postsolve_s = max(0, mpc_s - (mpc_state_cost_prep_s + mpc_dynamics_constraint_s + qp_s));
    end

    % Measured MPC Bucket B Sub-buckets (B1: Dynamics, B2: Block Torque, B3: Constraints)
    if isfield(p0, 'mpc_b1_robot_dynamics_s')
        mpc_b1_s = double(p0.mpc_b1_robot_dynamics_s);
        mpc_b2_s = double(p0.mpc_b2_block_torque_s);
        mpc_b3_s = double(p0.mpc_b3_constraint_assembly_s);
        mpc_b123_sum_s = double(p0.mpc_b123_sum_s);
        mpc_b123_rec_err_s = double(p0.mpc_b123_reconciliation_error_s);
    else
        mpc_b1_s = 0; mpc_b2_s = 0; mpc_b3_s = 0;
        mpc_b123_sum_s = 0; mpc_b123_rec_err_s = 0;
    end
    % Measured MPC B1 Sub-buckets (B1a: Kinematics, B1b: Mass Matrix, B1c: Bias/Friction)
    if isfield(p0, 'mpc_b1a_shared_kinematics_s')
        mpc_b1a_s = double(p0.mpc_b1a_shared_kinematics_s);
        mpc_b1b_s = double(p0.mpc_b1b_mass_matrix_s);
        mpc_b1c_s = double(p0.mpc_b1c_bias_friction_s);
        mpc_b1abc_sum_s = double(p0.mpc_b1abc_sum_s);
        mpc_b1abc_rec_err_s = double(p0.mpc_b1abc_reconciliation_error_s);
    else
        mpc_b1a_s = 0; mpc_b1b_s = 0; mpc_b1c_s = 0;
        mpc_b1abc_sum_s = 0; mpc_b1abc_rec_err_s = 0;
    end
else
    mpc_s = 0;
    plant_s = 0;
    qp_s = 0;
    ct_s = 0;
    ct_entries = 0;
    ct_mean_s = 0;
    mpc_state_cost_prep_s = 0;
    mpc_dynamics_constraint_s = 0;
    mpc_postsolve_s = 0;
    mpc_b1_s = 0;
    mpc_b2_s = 0;
    mpc_b3_s = 0;
    mpc_b123_sum_s = 0;
    mpc_b123_rec_err_s = 0;
    mpc_b1a_s = 0;
    mpc_b1b_s = 0;
    mpc_b1c_s = 0;
    mpc_b1abc_sum_s = 0;
    mpc_b1abc_rec_err_s = 0;
    n_entries = profile.logged_output_points * 7.5;
end

% MPC Macro reconciliation
measured_mpc_bucket_sum_s = mpc_state_cost_prep_s + mpc_dynamics_constraint_s + qp_s + mpc_postsolve_s;
measured_mpc_reconciliation_error_s = mpc_s - measured_mpc_bucket_sum_s;

% Bucket B Sub-bucket percentages
denom_bucket_b = max(1e-6, mpc_dynamics_constraint_s);
denom_wall = max(1e-6, sim_wall_s);
b1_pct_wall = (mpc_b1_s / denom_wall) * 100;
b1_pct_b = (mpc_b1_s / denom_bucket_b) * 100;
b2_pct_wall = (mpc_b2_s / denom_wall) * 100;
b2_pct_b = (mpc_b2_s / denom_bucket_b) * 100;
b3_pct_wall = (mpc_b3_s / denom_wall) * 100;
b3_pct_b = (mpc_b3_s / denom_bucket_b) * 100;

% Bucket B1 Sub-bucket percentages
denom_b1 = max(1e-6, mpc_b1_s);
b1a_pct_wall = (mpc_b1a_s / denom_wall) * 100;
b1a_pct_b1 = (mpc_b1a_s / denom_b1) * 100;
b1b_pct_wall = (mpc_b1b_s / denom_wall) * 100;
b1b_pct_b1 = (mpc_b1b_s / denom_b1) * 100;
b1c_pct_wall = (mpc_b1c_s / denom_wall) * 100;
b1c_pct_b1 = (mpc_b1c_s / denom_b1) * 100;

% -------------------------------------------------------------------------
% 1. MEASURED IN SIMULATION (Authoritative Timings - Preserves Signed Remainder)
% -------------------------------------------------------------------------
raw_unattributed_remainder_s = sim_wall_s - mpc_s - plant_s;

% Authoritative newly recomputed unattributed remainder with directly measured CT
newly_recomputed_unattributed_remainder_s = sim_wall_s - mpc_s - plant_s - ct_s;
is_negative_remainder = newly_recomputed_unattributed_remainder_s < 0;
if is_negative_remainder
    warnings{end+1} = sprintf('Instrumentation inconsistency: newly_recomputed_unattributed_remainder_s is negative (%+.4f s).', ...
        newly_recomputed_unattributed_remainder_s);
end

clipped_unattributed_remainder_s = max(0, newly_recomputed_unattributed_remainder_s);
pct_measured_unattributed = (raw_unattributed_remainder_s / max(1e-6, sim_wall_s)) * 100;
pct_newly_recomputed_unattributed = (newly_recomputed_unattributed_remainder_s / max(1e-6, sim_wall_s)) * 100;

measured_in_simulation = struct( ...
    'simulink_wall_s', sim_wall_s, ...
    'measured_mpc_total_s', mpc_s, ...
    'measured_mpc_pct', (mpc_s / max(1e-6, sim_wall_s)) * 100, ...
    'measured_qp_total_s', qp_s, ...
    'measured_qp_pct', (qp_s / max(1e-6, sim_wall_s)) * 100, ...
    'measured_mpc_state_cost_prep_s', mpc_state_cost_prep_s, ...
    'measured_mpc_state_cost_prep_pct', (mpc_state_cost_prep_s / max(1e-6, sim_wall_s)) * 100, ...
    'measured_mpc_dynamics_constraint_s', mpc_dynamics_constraint_s, ...
    'measured_mpc_dynamics_constraint_pct', (mpc_dynamics_constraint_s / max(1e-6, sim_wall_s)) * 100, ...
    'measured_mpc_b1_robot_dynamics_s', mpc_b1_s, ...
    'measured_mpc_b1_robot_dynamics_pct_wall', b1_pct_wall, ...
    'measured_mpc_b1_robot_dynamics_pct_bucket_b', b1_pct_b, ...
    'measured_mpc_b1a_shared_kinematics_s', mpc_b1a_s, ...
    'measured_mpc_b1a_shared_kinematics_pct_wall', b1a_pct_wall, ...
    'measured_mpc_b1a_shared_kinematics_pct_b1', b1a_pct_b1, ...
    'measured_mpc_b1b_mass_matrix_s', mpc_b1b_s, ...
    'measured_mpc_b1b_mass_matrix_pct_wall', b1b_pct_wall, ...
    'measured_mpc_b1b_mass_matrix_pct_b1', b1b_pct_b1, ...
    'measured_mpc_b1c_bias_friction_s', mpc_b1c_s, ...
    'measured_mpc_b1c_bias_friction_pct_wall', b1c_pct_wall, ...
    'measured_mpc_b1c_bias_friction_pct_b1', b1c_pct_b1, ...
    'measured_mpc_b1abc_sum_s', mpc_b1abc_sum_s, ...
    'measured_mpc_b1abc_reconciliation_error_s', mpc_b1abc_rec_err_s, ...
    'measured_mpc_b2_block_torque_s', mpc_b2_s, ...
    'measured_mpc_b2_block_torque_pct_wall', b2_pct_wall, ...
    'measured_mpc_b2_block_torque_pct_bucket_b', b2_pct_b, ...
    'measured_mpc_b3_constraint_assembly_s', mpc_b3_s, ...
    'measured_mpc_b3_constraint_assembly_pct_wall', b3_pct_wall, ...
    'measured_mpc_b3_constraint_assembly_pct_bucket_b', b3_pct_b, ...
    'measured_mpc_b123_sum_s', mpc_b123_sum_s, ...
    'measured_mpc_b123_reconciliation_error_s', mpc_b123_rec_err_s, ...
    'measured_mpc_postsolve_s', mpc_postsolve_s, ...
    'measured_mpc_postsolve_pct', (mpc_postsolve_s / max(1e-6, sim_wall_s)) * 100, ...
    'measured_mpc_bucket_sum_s', measured_mpc_bucket_sum_s, ...
    'measured_mpc_reconciliation_error_s', measured_mpc_reconciliation_error_s, ...
    'measured_plant_total_s', plant_s, ...
    'measured_plant_pct', (plant_s / max(1e-6, sim_wall_s)) * 100, ...
    'measured_computed_torque_total_s', ct_s, ...
    'measured_computed_torque_pct', (ct_s / max(1e-6, sim_wall_s)) * 100, ...
    'computed_torque_call_count', ct_entries, ...
    'computed_torque_mean_s_per_call', ct_mean_s, ...
    'raw_unattributed_remainder_s', raw_unattributed_remainder_s, ...
    'raw_unattributed_remainder_pct', pct_measured_unattributed, ...
    'newly_recomputed_unattributed_remainder_s', newly_recomputed_unattributed_remainder_s, ...
    'newly_recomputed_unattributed_remainder_pct', pct_newly_recomputed_unattributed, ...
    'clipped_unattributed_remainder_s', clipped_unattributed_remainder_s, ...
    'negative_remainder_detected', is_negative_remainder, ...
    'controller_entry_count', n_entries);

% -------------------------------------------------------------------------
% 2. OFFLINE ESTIMATES (Non-Authoritative Profiling Microbenchmarks)
% -------------------------------------------------------------------------
% 2.1 Micro-benchmark Computed_Torque (inverse_dynamics_kinova_MR) - Retained for comparison only
n_samples = min(500, size(telemetry.q, 2));
sample_indices = round(linspace(1, size(telemetry.q, 2), n_samples));
Mlist = models.Mlist_nom; Glist = models.Glist_nom; Slist = models.Slist_nom;

ct_tic = tic;
for i = 1:n_samples
    idx = sample_indices(i);
    qi = telemetry.q(:, idx);
    dqi = telemetry.dq(:, idx);
    vi = zeros(6, 1);
    inverse_dynamics_kinova_MR(qi, dqi, vi, Mlist, Glist, Slist);
end
ct_bench_s = toc(ct_tic);
mean_ct_call_s = ct_bench_s / n_samples;
estimated_computed_torque_s = mean_ct_call_s * n_entries;

% 2.2 Context Access Timing (Blocker 1: Use in-simulation benchmark or safe reinstall)
if isfield(profile, 'benchmarked_ctx_call_us') && ~isempty(profile.benchmarked_ctx_call_us) && ...
        profile.benchmarked_ctx_call_us > 0
    mean_ctx_call_s = double(profile.benchmarked_ctx_call_us) * 1e-6;
    ctx_source = 'CAPTURED_DURING_SIMULATION_ACTIVE_CONTEXT';
elseif ~isempty(opt_prep)
    % Temporarily install captured context, benchmark, and deterministically clear
    shape.mpc_runtime_context('set', opt_prep);
    ctx_cleanup = onCleanup(@() shape.mpc_runtime_context('clear'));
    ctx_runs = 5000;
    ctx_tic = tic;
    for i = 1:ctx_runs
        shape.mpc_runtime_context('get');
    end
    mean_ctx_call_s = toc(ctx_tic) / ctx_runs;
    clear ctx_cleanup;
    ctx_source = 'REINSTALLED_DETERMINISTIC_BENCHMARK';
else
    mean_ctx_call_s = 0.5e-6; % Fallback 0.5 us conservative estimate
    ctx_source = 'THEORETICAL_ESTIMATE_CONTEXT_UNAVAILABLE';
    warnings{end+1} = 'Runtime context not supplied for offline benchmark; using 0.5 us fallback.';
end

estimated_context_access_s = mean_ctx_call_s * n_entries;

offline_estimates = struct( ...
    'estimated_computed_torque_s', estimated_computed_torque_s, ...
    'estimated_computed_torque_pct', (estimated_computed_torque_s / max(1e-6, sim_wall_s)) * 100, ...
    'benchmarked_ct_call_us', mean_ct_call_s * 1e6, ...
    'estimated_context_access_s', estimated_context_access_s, ...
    'estimated_context_access_pct', (estimated_context_access_s / max(1e-6, sim_wall_s)) * 100, ...
    'benchmarked_ctx_call_us', mean_ctx_call_s * 1e6, ...
    'context_benchmark_source', ctx_source);

% -------------------------------------------------------------------------
% 3. ESTIMATED REMAINDER CALCULATION (Model-Based Decomposition)
% -------------------------------------------------------------------------
% Newly recomputed unattributed remainder already accounts for directly measured Computed_Torque.
% Subtract only remaining offline context access.
raw_estimated_unattributed_remainder_s = newly_recomputed_unattributed_remainder_s - estimated_context_access_s;
clipped_estimated_unattributed_remainder_s = max(0, raw_estimated_unattributed_remainder_s);
pct_estimated_remainder = (raw_estimated_unattributed_remainder_s / max(1e-6, sim_wall_s)) * 100;

estimated_decomposition = struct( ...
    'raw_estimated_unattributed_remainder_s', raw_estimated_unattributed_remainder_s, ...
    'raw_estimated_unattributed_remainder_pct', pct_estimated_remainder, ...
    'clipped_estimated_unattributed_remainder_s', clipped_estimated_unattributed_remainder_s, ...
    'offline_ct_comparison_diff_s', ct_s - estimated_computed_torque_s, ...
    'note', 'Model calculation: newly_recomputed_unattributed - estimated_ctx. Retains offline CT comparison only.');

% -------------------------------------------------------------------------
% 4. EVIDENCE & TAXONOMY SUMMARY
% -------------------------------------------------------------------------
evidence_table = { ...
    struct('component', 'Flatness_MPC (Controller)', 'timing_s', mpc_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Direct in-simulation profiling via P0 in solve_flatness_mpc_step_MR'); ...
    struct('component', 'MPC State & Cost Prep (Macro Bucket A)', 'timing_s', mpc_state_cost_prep_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Direct in-simulation profiling of cache, reference, and linear cost'); ...
    struct('component', 'MPC Dynamics & Constraints (Macro Bucket B)', 'timing_s', mpc_dynamics_constraint_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Direct in-simulation profiling of dynamics, M_blk, and constraint matrix assembly'); ...
    struct('component', '  [Bucket B1] Robot Dynamics (Macro Bucket)', 'timing_s', mpc_b1_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Direct in-simulation profiling of RNEA kinematics, zero-state mass matrix, ID bias, friction'); ...
    struct('component', '    [Sub-bucket B1a] Shared Kinematics (kin)', 'timing_s', mpc_b1a_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Direct in-simulation profiling of rnea_shared_kinematics_MR'); ...
    struct('component', '    [Sub-bucket B1b] Mass Matrix & M_dyn', 'timing_s', mpc_b1b_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Direct in-simulation profiling of MassMatrixZeroStateSharedKinematics_MR + J_rotors'); ...
    struct('component', '    [Sub-bucket B1c] Bias Inverse Dynamics & Friction', 'timing_s', mpc_b1c_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Direct in-simulation profiling of InverseDynamicsSharedKinematics_MR + nominal friction'); ...
    struct('component', '  [Bucket B2] Block Mass & Torque Constraints (Retired in B1-Sub pass)', 'timing_s', mpc_b2_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Inner timer retired to minimize timer overhead; preserved for schema compatibility'); ...
    struct('component', '  [Bucket B3] Remaining Constraint & Bounds Assembly (Retired in B1-Sub pass)', 'timing_s', mpc_b3_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Inner timer retired to minimize timer overhead; preserved for schema compatibility'); ...
    struct('component', 'MPC QP Active-Set Solve (Macro Bucket C)', 'timing_s', qp_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Direct in-simulation profiling of quadprog'); ...
    struct('component', 'MPC Postsolve Reconstruction (Macro Bucket D)', 'timing_s', mpc_postsolve_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Direct in-simulation profiling of control output reconstruction'); ...
    struct('component', 'Plant RHS (State-Space)', 'timing_s', plant_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Direct in-simulation profiling via P0 in kinova_state_space_sucia_MR'); ...
    struct('component', 'Computed_Torque (Inverse Dynamics)', 'timing_s', ct_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Direct in-simulation profiling via P0 in inverse_dynamics_kinova_MR'); ...
    struct('component', 'Newly Recomputed Unattributed Walltime Remainder (Signed)', 'timing_s', newly_recomputed_unattributed_remainder_s, ...
        'timing_category', 'MEASURED_IN_SIMULATION', 'evidence_level', 'EVIDENCED', ...
        'method', 'Exact measured difference: sim_wall_s - mpc_s - plant_s - ct_s (authoritative signed quantity)'); ...
    struct('component', 'Host Context Access (mpc_runtime_context)', 'timing_s', estimated_context_access_s, ...
        'timing_category', 'OFFLINE_ESTIMATE', 'evidence_level', 'EVIDENCED', ...
        'method', sprintf('Context get benchmark (%s) scaled by controller entries', ctx_source)); ...
    struct('component', 'Diagnostic Comparison: Offline Computed_Torque', 'timing_s', estimated_computed_torque_s, ...
        'timing_category', 'OFFLINE_ESTIMATE', 'evidence_level', 'EVIDENCED', ...
        'method', 'Offline microbenchmark comparison only (not driving primary residual)'); ...
    struct('component', 'Estimated Residual Walltime Remainder (Signed)', 'timing_s', raw_estimated_unattributed_remainder_s, ...
        'timing_category', 'CALCULATED_ESTIMATE', 'evidence_level', 'UNKNOWN', ...
        'method', 'Calculated difference: newly_recomputed_unattributed - estimated_ctx') ...
};

diag = struct();
diag.simulink_wall_s = sim_wall_s;
diag.measured_in_simulation = measured_in_simulation;
diag.offline_estimates = offline_estimates;
diag.estimated_decomposition = estimated_decomposition;
diag.evidence_table = evidence_table;
diag.warnings = warnings;

end
